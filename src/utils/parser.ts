/**
 * Parse pasted text or raw string input
 * Handles:
 * - Line breaks (\n, \r\n)
 * - Commas, tabs, semicolons
 * - Leading numbers like "01. 張三", "2、李四", "(3) 王五"
 */
export function parsePastedNames(text: string): Student[] {
  if (!text || !text.trim()) return [];

  // Split by newlines, commas, tabs, or semicolons
  const lines = text
    .split(/[\r\n,;]+/)
    .map((l) => l.trim())
    .filter(Boolean);

  const students: Student[] = [];

  lines.forEach((line, index) => {
    // Regex to detect prefix like "1.", "01 ", "(1)", "1、", "No.1"
    const prefixMatch = line.match(/^(\(?\d+\)?|[0-9]+[、.．:]|\bNo\.\s*\d+)?\s*(.+)$/i);
    let extractedNumber = '';
    let extractedName = line;

    if (prefixMatch && prefixMatch[2]) {
      const rawNum = prefixMatch[1] ? prefixMatch[1].replace(/[^\d]/g, '') : '';
      if (rawNum) {
        extractedNumber = rawNum.padStart(2, '0');
      }
      extractedName = prefixMatch[2].trim();
    }

    // Check if line itself has a tab or comma separating number and name
    const parts = extractedName.split(/[\t,，\s]+/);
    if (parts.length >= 2 && /^\d+$/.test(parts[0])) {
      extractedNumber = parts[0].padStart(2, '0');
      extractedName = parts.slice(1).join(' ').trim();
    }

    if (extractedName) {
      students.push({
        id: `stu-${Date.now()}-${index}-${Math.random().toString(36).slice(2, 6)}`,
        number: extractedNumber || String(students.length + 1).padStart(2, '0'),
        name: extractedName,
      });
    }
  });

  return students;
}

/**
 * Parse CSV content with header and column detection
 */
export function parseCSVContent(content: string): Student[] {
  if (!content || !content.trim()) return [];

  const rawLines = content.split(/\r\n|\n|\r/).map((l) => l.trim()).filter(Boolean);
  if (rawLines.length === 0) return [];

  // Simple CSV line parser supporting quoted fields
  const parseLine = (line: string): string[] => {
    const result: string[] = [];
    let current = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"') {
        inQuotes = !inQuotes;
      } else if (char === ',' && !inQuotes) {
        result.push(current.trim().replace(/^"|"$/g, ''));
        current = '';
      } else {
        current += char;
      }
    }
    result.push(current.trim().replace(/^"|"$/g, ''));
    return result;
  };

  const rows = rawLines.map(parseLine);
  if (rows.length === 0) return [];

  // Check if first row is a header
  const firstRow = rows[0];
  let nameColIdx = 0;
  let numColIdx = -1;
  let hasHeader = false;

  const headerKeywordsName = ['姓名', '學生姓名', '名字', 'name', 'student_name', 'student'];
  const headerKeywordsNum = ['座號', '學號', '編號', '號碼', 'number', 'id', 'no'];

  firstRow.forEach((col, idx) => {
    const lower = col.toLowerCase().trim();
    if (headerKeywordsName.some((k) => lower.includes(k))) {
      nameColIdx = idx;
      hasHeader = true;
    }
    if (headerKeywordsNum.some((k) => lower.includes(k))) {
      numColIdx = idx;
      hasHeader = true;
    }
  });

  // If first row doesn't have obvious header keyword, but has 2 columns where first is number and second is string:
  if (!hasHeader && firstRow.length >= 2) {
    if (/^\d+$/.test(firstRow[0]) && !/^\d+$/.test(firstRow[1])) {
      numColIdx = 0;
      nameColIdx = 1;
    }
  }

  const dataRows = hasHeader ? rows.slice(1) : rows;
  const students: Student[] = [];

  dataRows.forEach((row, idx) => {
    const rawName = row[nameColIdx] || row[0] || '';
    if (!rawName.trim()) return;

    let num = '';
    if (numColIdx !== -1 && row[numColIdx]) {
      num = row[numColIdx].trim();
    } else {
      num = String(students.length + 1).padStart(2, '0');
    }

    students.push({
      id: `stu-${Date.now()}-${idx}-${Math.random().toString(36).slice(2, 6)}`,
      number: num,
      name: rawName.trim(),
    });
  });

  return students;
}
